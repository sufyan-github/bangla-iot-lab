import { eq } from 'drizzle-orm';
import pg from 'pg';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildApp } from '../app';
import { DEV_DATABASE_URL, loadConfig } from '../config';
import { createDatabase, runMigrations, type Database } from './client';
import * as s from './schema';

/**
 * Runs against a real PostgreSQL 18 (`pnpm db:up`). Uses its own database,
 * recreated on every run, so it never touches development data.
 */
const baseUrl = process.env.DATABASE_URL ?? DEV_DATABASE_URL;
const testUrl = new URL(baseUrl);
testUrl.pathname = '/banglalab_test';

let database: Database;

beforeAll(async () => {
  const admin = new pg.Client({ connectionString: baseUrl });
  await admin.connect().catch((error: Error) => {
    throw new Error(
      `PostgreSQL is not reachable at ${new URL(baseUrl).host}. Run "pnpm db:up". (${error.message})`,
    );
  });
  await admin.query('DROP DATABASE IF EXISTS banglalab_test WITH (FORCE)');
  await admin.query('CREATE DATABASE banglalab_test');
  await admin.end();

  database = createDatabase(testUrl.toString());
  await runMigrations(database);
});
afterAll(() => database?.pool.end());

/** Runs a query that must be refused and returns the name of the violated constraint. */
async function violated(query: Promise<unknown>): Promise<string | undefined> {
  const error = await query.then(
    () => null,
    (e: { cause?: { constraint?: string } }) => e,
  );
  if (!error) throw new Error('expected the database to refuse this row');
  return error.cause?.constraint;
}

describe('initial schema on PostgreSQL 18', () => {
  it('applies migrations idempotently', async () => {
    await runMigrations(database);
    const { rows } = await database.pool.query(
      "select count(*)::int as n from information_schema.tables where table_schema = 'public'",
    );
    expect(rows[0].n).toBe(15);
  });

  it('stores a school, a teacher, a class and a pseudonymous learner', async () => {
    const { db } = database;
    const [school] = await db.insert(s.schools).values({ name: 'পরীক্ষা উচ্চ বিদ্যালয়' }).returning();
    const [teacher] = await db
      .insert(s.users)
      .values({ kind: 'adult', displayName: 'শিক্ষক', email: 'Teacher@Example.test' })
      .returning();
    const [learner] = await db
      .insert(s.users)
      .values({ kind: 'learner', displayName: 'তারা-১২' })
      .returning();
    await db
      .insert(s.schoolMemberships)
      .values({ schoolId: school!.id, userId: teacher!.id, role: 'teacher' });
    const [klass] = await db
      .insert(s.classes)
      .values({ schoolId: school!.id, teacherId: teacher!.id, name: 'অষ্টম ক', grade: 8 })
      .returning();
    await db
      .insert(s.classEnrollments)
      .values({ classId: klass!.id, learnerId: learner!.id, pseudonym: 'তারা-১২' });

    // UUIDv7 keys are generated by the database and sort by creation time.
    expect(school!.id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-7/);
    expect(teacher!.id < learner!.id).toBe(true);
    expect(learner!.locale).toBe('bn');

    // --- constraints that protect children's data and class integrity ---
    expect(
      await violated(
        db
          .insert(s.users)
          .values({ kind: 'learner', displayName: 'x', email: 'child@example.test' }),
      ),
    ).toBe('users_learner_has_no_contact_details');
    expect(
      await violated(
        db
          .insert(s.users)
          .values({ kind: 'learner', displayName: 'x', platformRole: 'platform_admin' }),
      ),
    ).toBe('users_learner_has_no_platform_role');
    expect(
      await violated(
        db
          .insert(s.users)
          .values({ kind: 'adult', displayName: 'dup', email: 'teacher@example.test' }),
      ),
    ).toBe('users_email_unique');
    expect(
      await violated(
        db
          .insert(s.schoolMemberships)
          .values({ schoolId: school!.id, userId: teacher!.id, role: 'teacher' }),
      ),
    ).toBe('school_memberships_unique');
    expect(
      await violated(
        db
          .insert(s.classes)
          .values({ schoolId: school!.id, teacherId: teacher!.id, name: 'x', grade: 5 }),
      ),
    ).toBe('classes_grade_range');
    expect(
      await violated(
        db
          .insert(s.classEnrollments)
          .values({ classId: klass!.id, learnerId: teacher!.id, pseudonym: 'তারা-১২' }),
      ),
    ).toBe('class_enrollments_pseudonym_unique');
    // A school with members cannot be deleted out from under them.
    expect(await violated(db.delete(s.schools).where(eq(s.schools.id, school!.id)))).toMatch(
      /_school_id_schools_id_fk$/,
    );
  });

  it('versions projects and cascades versions with their project', async () => {
    const { db } = database;
    const [owner] = await db
      .insert(s.users)
      .values({ kind: 'learner', displayName: 'নদী-৭' })
      .returning();
    const [project] = await db
      .insert(s.projects)
      .values({ ownerId: owner!.id, title: 'LED' })
      .returning();
    const document = { schemaVersion: 1, components: [], wires: [] };
    const version = { projectId: project!.id, schemaVersion: 1, document };
    await db.insert(s.projectVersions).values({ ...version, version: 1 });
    expect(await violated(db.insert(s.projectVersions).values({ ...version, version: 1 }))).toBe(
      'project_versions_unique',
    );
    expect(await violated(db.insert(s.projectVersions).values({ ...version, version: 0 }))).toBe(
      'project_versions_positive',
    );

    const [stored] = await db
      .select()
      .from(s.projectVersions)
      .where(eq(s.projectVersions.projectId, project!.id));
    expect(stored!.document).toEqual(document);

    await db.delete(s.projects).where(eq(s.projects.id, project!.id));
    expect(
      await db.select().from(s.projectVersions).where(eq(s.projectVersions.projectId, project!.id)),
    ).toEqual([]);
  });

  it('keeps audit entries when their actor is removed', async () => {
    const { db } = database;
    const [actor] = await db
      .insert(s.users)
      .values({ kind: 'adult', displayName: 'temp' })
      .returning();
    const [entry] = await db
      .insert(s.auditLogs)
      .values({ actorId: actor!.id, action: 'class.create' })
      .returning();
    await db.delete(s.users).where(eq(s.users.id, actor!.id));
    const [kept] = await db.select().from(s.auditLogs).where(eq(s.auditLogs.id, entry!.id));
    expect(kept).toMatchObject({ action: 'class.create', actorId: null });
  });

  it('reports ready through the API when the database is up', async () => {
    const app = await buildApp({
      config: loadConfig({ LOG_LEVEL: 'silent' }),
      database,
      fetch: async () => new Response('{}'),
    });
    const response = await app.inject('/ready');
    await app.close();
    expect(response.statusCode).toBe(200);
    expect(response.json().database).toBe('ok');
  });
});
