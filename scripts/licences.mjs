// Checks and records the licences of everything this project ships.
//
//   node scripts/licences.mjs check   fails if a shipped dependency is not on the allowed list
//   node scripts/licences.mjs write   regenerates THIRD_PARTY_LICENSES.md
//
// "Shipped" means production dependencies: the web client's, and the servers'.
// Build tools are not distributed and are not checked. Copyleft licences (GPL,
// AGPL, LGPL, MPL and the like) are refused here; the one place LGPL code is
// distributed, the starter firmware, is handled separately and on purpose in
// third_party/arduino-avr/README.md.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ALLOWED = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'OFL-1.1',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'Unlicense',
]);

function list(filter) {
  const args = [...(filter ? ['--filter', filter] : []), 'licenses', 'list', '--prod', '--json'];
  const byLicence = JSON.parse(execFileSync('pnpm', args, { encoding: 'utf8', maxBuffer: 64e6 }));
  return Object.entries(byLicence).flatMap(([licence, packages]) =>
    packages.map((pkg) => ({ ...pkg, licence })),
  );
}

/** A dual-licensed package is fine if any of its choices is allowed. */
const isAllowed = (licence) =>
  licence
    .replace(/[()]/g, '')
    .split(/\s+OR\s+/i)
    .some((choice) => ALLOWED.has(choice.trim()));

function check() {
  const scopes = [
    ['web client', '@banglalab/web'],
    ['whole workspace', null],
  ];
  let failed = false;
  for (const [label, filter] of scopes) {
    const packages = list(filter);
    const refused = packages.filter((pkg) => !isAllowed(pkg.licence));
    console.log(`${label}: ${packages.length} shipped packages, ${refused.length} refused`);
    for (const pkg of refused) {
      failed = true;
      console.error(`  refused: ${pkg.name} ${pkg.versions.join(', ')} is ${pkg.licence}`);
    }
  }
  if (failed) {
    console.error('\nA shipped dependency has a licence that is not on the allowed list.');
    console.error('Remove it, or get a decision recorded before adding the licence to ALLOWED.');
    process.exit(1);
  }
}

function licenceText(directory) {
  if (!existsSync(directory)) return null;
  const file = readdirSync(directory).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  return file ? readFileSync(path.join(directory, file), 'utf8').trim() : null;
}

function write() {
  const packages = list(null).sort((a, b) => a.name.localeCompare(b.name));
  // Many packages share one licence text word for word; print each text once.
  const texts = new Map();
  for (const pkg of packages) {
    const text =
      licenceText(pkg.paths[0]) ?? `(no licence file in the package; declared ${pkg.licence})`;
    const key = createHash('sha256').update(text.replace(/\s+/g, ' ')).digest('hex');
    const entry = texts.get(key) ?? { text, packages: [] };
    entry.packages.push(pkg);
    texts.set(key, entry);
  }
  const lines = [
    '# Third-party licences',
    '',
    'Generated by `node scripts/licences.mjs write`. Do not edit by hand.',
    '',
    'These are the production dependencies of the web client and the servers.',
    'The starter firmware and the Bangla font are covered in `NOTICE`.',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...packages.map((pkg) => `| ${pkg.name} | ${pkg.versions.join(', ')} | ${pkg.licence} |`),
    '',
  ];
  for (const { text, packages: group } of texts.values()) {
    lines.push(`## ${group.map((pkg) => pkg.name).join(', ')}`, '', '```text', text, '```', '');
  }
  writeFileSync('THIRD_PARTY_LICENSES.md', lines.join('\n'));
  console.log(
    `Wrote THIRD_PARTY_LICENSES.md: ${packages.length} packages, ${texts.size} licence texts.`,
  );
}

const command = process.argv[2];
if (command === 'check') check();
else if (command === 'write') write();
else {
  console.error('usage: node scripts/licences.mjs check|write');
  process.exit(2);
}
